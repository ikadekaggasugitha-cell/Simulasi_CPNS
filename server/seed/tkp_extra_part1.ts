import type { OptionKey, SeedQuestion, TkpWeights } from './types';

// Ranked options strictly from score 5 (best) down to score 1 (worst)
export type RawTkpTuple = [
  subtopik: string,
  pertanyaan: string,
  rankedOpts5To1: [string, string, string, string, string],
  pembahasan: string
];

const PERMS: ReadonlyArray<readonly [number, number, number, number, number]> = [
  [0, 1, 2, 3, 4],
  [2, 0, 4, 1, 3],
  [4, 2, 0, 3, 1],
  [1, 3, 2, 0, 4],
  [3, 4, 1, 2, 0],
  [0, 3, 1, 4, 2],
  [1, 0, 3, 4, 2],
  [2, 4, 0, 3, 1],
  [3, 1, 4, 0, 2],
  [4, 0, 2, 1, 3],
  [1, 4, 3, 2, 0],
  [2, 1, 3, 0, 4],
];

export function buildTkpQuestions(items: RawTkpTuple[], seedOffset = 0): SeedQuestion[] {
  const keys: OptionKey[] = ['A', 'B', 'C', 'D', 'E'];
  return items.map(([subtopik, pertanyaan, rankedOpts, pembahasan], i) => {
    const perm = PERMS[(seedOffset + i * 5 + (pertanyaan.length % PERMS.length)) % PERMS.length];
    // perm[slot] = rankIndex (0 => weight 5, 1 => weight 4, ..., 4 => weight 1)
    const opts = perm.map((rankIdx) => rankedOpts[rankIdx]);
    const weights: Record<OptionKey, number> = {
      A: 5 - perm[0],
      B: 5 - perm[1],
      C: 5 - perm[2],
      D: 5 - perm[3],
      E: 5 - perm[4],
    };
    const bestSlot = perm.indexOf(0);
    return {
      kategori: 'TKP',
      subtopik,
      pertanyaan,
      opsi_a: opts[0],
      opsi_b: opts[1],
      opsi_c: opts[2],
      opsi_d: opts[3],
      opsi_e: opts[4],
      jawaban_benar: keys[bestSlot],
      bobot_tkp: weights as TkpWeights,
      pembahasan,
    };
  });
}

